#!/usr/bin/env python3
"""Round-2 assembler (read-only helper; NOT part of tools/blkhtml).

Consumes the blk2bin --emit-c fragment (tool-produced, corrected) and wraps
it into kernel_v25/src/gui/blkgen.c:
  * verbatim blk_spec blocks from the fragment;
  * a non-root blk_desc array (id=0 root excluded, per decl contract);
  * bridge: root 800x600, gui_commit_desc, dirty marking, layout_run,
    serial BLKGEN geometry dump.

No kind/color mapping lives here: the tool emits correct role_* enums and
INHERIT_COLOR already.
"""
import re, sys, hashlib, json

FRAG = sys.argv[1]      # tool-produced .c fragment
JSON = sys.argv[2]      # source .blk.json (for sha + root exclusion check)
OUT = sys.argv[3]

frag = open(FRAG, encoding="utf-8").read()

sha = hashlib.sha256(open(JSON, "rb").read()).hexdigest()

# --- extract verbatim spec blocks -----------------------------------------
spec_re = re.compile(r"static blk_spec (spec_\d+) = \{.*?\};", re.S)
specs = [(m.group(1), m.group(0)) for m in spec_re.finditer(frag)]

# --- extract desc initializer lines --------------------------------------
desc_re = re.compile(
    r"\{\s*\.id\s*=\s*(\d+),\s*\.kind\s*=\s*(\w+),\s*\.parent\s*=\s*(\d+),"
    r"\s*\.spec\s*=\s*&(spec_\d+),\s*\.text\s*=\s*(0|\"[^\"]*\"),"
    r"\s*\.pix\s*=\s*\d+,\s*\.pix_w\s*=\s*\d+,\s*\.pix_h\s*=\s*\d+\s*\},")
descs = []
for m in desc_re.finditer(frag):
    descs.append({
        "id": int(m.group(1)), "kind": m.group(2), "parent": int(m.group(3)),
        "spec": m.group(4), "text": m.group(5),
    })

non_root = [d for d in descs if d["id"] != 0]
assert non_root, "no non-root descs parsed"

lines = []
lines.append("/* AUTO-GENERATED by run2/assemble_blkgen.py from blk2bin --emit-c")
lines.append(" * source: %s" % JSON)
lines.append(" * sha256: %s" % sha)
lines.append(" * bridge glue: root exclusion / dirty marking / geometry dump.")
lines.append(" * Color and kind values come verbatim from the tool fragment.")
lines.append(" */")
lines.append('#include "gui/gui.h"')
lines.append('#include "gui_int.h"')
lines.append('#include "serial_log.h"')
lines.append("")
lines.append("static void blkgen_put_dec(int32_t v) {")
lines.append("    char b[12]; int n = 0;")
lines.append("    if (v < 0) { ser_putc('-'); v = -v; }")
lines.append("    if (v == 0) { ser_putc('0'); return; }")
lines.append("    while (v) { b[n++] = (char)('0' + v % 10); v /= 10; }")
lines.append("    while (n) ser_putc(b[--n]);")
lines.append("}")
lines.append("")

for _, body in specs:
    lines.append(body)
    lines.append("")

lines.append("static const blk_desc blkgen_descs[] = {")
for d in non_root:
    lines.append(
        "    { .id = %d, .kind = %s, .parent = %d, .spec = &%s, .text = %s,"
        " .pix = 0, .pix_w = 0, .pix_h = 0 },"
        % (d["id"], d["kind"], d["parent"], d["spec"], d["text"]))
lines.append("};")
lines.append("")

lines.append("int blkgen_build(void) {")
lines.append("    block *root = gui_root_block();")
lines.append("    root->w = 800; root->h = 600;")
lines.append("    gui_commit_desc(blkgen_descs,"
              " sizeof(blkgen_descs) / sizeof(blkgen_descs[0]));")
lines.append("    for (uint32_t i = 0; i < sizeof(blkgen_descs) /")
lines.append("                     sizeof(blkgen_descs[0]); i++)")
lines.append("        gui_mark_dirty(blkgen_descs[i].id);")
lines.append("    gui_mark_dirty(root->id);")
lines.append("    layout_run();")
lines.append("")
lines.append("    uint32_t cap = btable_capacity();")
lines.append("    for (uint32_t id = 1; id <= cap; id++) {")
lines.append("        block *b = btable_get(id);")
lines.append("        if (!b) continue;")
lines.append("        ser_write(\"BLKGEN id=\"); blkgen_put_dec(b->id);")
lines.append("        ser_write(\" x=\"); blkgen_put_dec(b->x);")
lines.append("        ser_write(\" y=\"); blkgen_put_dec(b->y);")
lines.append("        ser_write(\" w=\"); blkgen_put_dec(b->w);")
lines.append("        ser_write(\" h=\"); blkgen_put_dec(b->h);")
lines.append("        ser_write(\"\\n\");")
lines.append("    }")
lines.append("    return 0;")
lines.append("}")

open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote %s: %d specs, %d non-root descs" % (OUT, len(specs), len(non_root)))
