#!/usr/bin/env python3
"""Auxiliary read-only generator (NOT part of tools/blkhtml).

Reads blk2bin-produced recs.bin / strings.bin and emits
kernel_v25/extapp/blkgen.c:

  * batch RAW  : faithful CE mirror of the .blk.json (root id=0 record
                  excluded; parent=0 attaches to the per-app root).
  * batch PROJ : same tree, but kinds that slot 72 rejects
                  (BUTTON=12 / INPUT=13 / TERM=14 / FREE=11) are downgraded
                  to RECT=5, to show what the CE channel can actually render.

The app commits both batches through slot 72 (blk_commit) and prints the
verdict to the console / serial.  Geometry, colors, radius and shadow are
NOT carried by ce_blk_rec_t by design (schema :: ce_projection).
"""
import json
import struct
import sys

REC_FMT = "<iiBBHiiiiiii"
REC_BYTES = 40
# kinds slot 72 accepts: BLK_COLUMN(1) .. BLK_CANVAS(10) (decl.c validate).
CE_LEGAL_MAX = 10
DOWNGRADE = {12: 5, 13: 5, 11: 5, 14: 5}  # button/input/free/term -> rect


def parse_recs(path):
    data = open(path, "rb").read()
    out = []
    for i in range(0, len(data), REC_BYTES):
        out.append(struct.unpack(REC_FMT, data[i:i + REC_BYTES]))
    return out


def c_str_lit(raw: bytes) -> str:
    out = ['"']
    for b in raw:
        if b == 0:
            out.append("\\0")
        elif b == ord("\\"):
            out.append("\\\\")
        elif b == ord('"'):
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    out.append('"')
    return "".join(out)


def rec_initializer(r):
    return "    { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d }," % r


def main():
    recs_path, pool_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
    recs = parse_recs(recs_path)
    pool = open(pool_path, "rb").read()

    # exclude root record id=0 (CE contract: ids >=1, parent=0 -> app root)
    mirror = [r for r in recs if r[0] != 0]
    proj = [tuple(DOWNGRADE.get(r[2], r[2]) if i == 2 else v
                  for i, v in enumerate(r)) for r in mirror]

    lines = []
    lines.append("/* AUTO-GENERATED by artifacts/gui-tools/run/gen_blkgen_ce.py")
    lines.append(" * do not edit by hand.  CE slot 72 structural-probe app.")
    lines.append(" */")
    lines.append("#include \"ce_app.h\"")
    lines.append("")
    lines.append("static const ce_blk_rec_t raw_recs[] = {")
    for r in mirror:
        lines.append(rec_initializer(r))
    lines.append("};")
    lines.append("")
    lines.append("static const ce_blk_rec_t proj_recs[] = {")
    for r in proj:
        lines.append(rec_initializer(r))
    lines.append("};")
    lines.append("")
    lines.append("static const char blk_pool[] = %s;" % c_str_lit(pool))
    lines.append("")
    lines.append("static void blkgen_ce_put_int(int v) {")
    lines.append("    char b[12]; int n = 0; unsigned int u;")
    lines.append("    if (v < 0) { ce_write(\"-\"); u = (unsigned int)(-(int)v); }")
    lines.append("    else u = (unsigned int)v;")
    lines.append("    if (u == 0) { ce_write(\"0\"); return; }")
    lines.append("    while (u) { b[n++] = (char)('0' + u % 10); u /= 10; }")
    lines.append("    while (n) ce_putc(b[--n]);")
    lines.append("}")
    lines.append("")
    lines.append("__attribute__((section(\".text.ce_entry\")))")
    lines.append("int ce_main(int argc, char **argv) {")
    lines.append("    (void)argc; (void)argv;")
    lines.append("    catos_api_t *api = ce_api();")
    lines.append("    int n = (int)(sizeof(raw_recs) / sizeof(raw_recs[0]));")
    lines.append("")
    lines.append("    ce_write(\"BLKGEN_CE raw: commit=\\n\");")
    lines.append("    int rc_raw = api->blk_commit(raw_recs, n, blk_pool,")
    lines.append("                                 (int)sizeof(blk_pool) - 1);")
    lines.append("    ce_write(\"BLKGEN_CE raw rc=\");")
    lines.append("    blkgen_ce_put_int(rc_raw); ce_write(\" n=\");")
    lines.append("    blkgen_ce_put_int(n); ce_write(\"\\n\");")
    lines.append("")
    lines.append("    ce_write(\"BLKGEN_CE proj: commit=\\n\");")
    lines.append("    int rc_proj = api->blk_commit(proj_recs, n, blk_pool,")
    lines.append("                                  (int)sizeof(blk_pool) - 1);")
    lines.append("    ce_write(\"BLKGEN_CE proj rc=\");")
    lines.append("    blkgen_ce_put_int(rc_proj); ce_write(\" n=\");")
    lines.append("    blkgen_ce_put_int(n); ce_write(\"\\n\");")
    lines.append("")
    lines.append("    ce_blk_event_t ev;")
    lines.append("    int polled = api->blk_event_poll(&ev, 0);")
    lines.append("    ce_write(\"BLKGEN_CE poll=\");")
    lines.append("    blkgen_ce_put_int(polled); ce_write(\"\\n\");")
    lines.append("    return 0;")
    lines.append("}")
    lines.append("")

    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote %s (raw=%d proj=%d pool=%d)" % (out, len(mirror), len(proj),
                                                 len(pool)))


if __name__ == "__main__":
    main()
