#!/usr/bin/env python3
"""ttf_gen_expect.py -- v2.55-ttf crosscheck expectation generator.

Uses fontTools to dump, for two reference TrueType fonts, the ground-truth
of the fields our minimal parser must reproduce:
  - cmap: unicode 'A' (0x41) / 'g' (0x67) -> glyph id
  - hmtx: advance width of those glyphs (font units)
  - glyf: raw coordinate list (x, y, on-curve flag) of each glyph

Writes a C header consumed by tests/ttf_host_test.c, so the host unit test
compares parser output point-by-point against fontTools.

usage: ttf_gen_expect.py <out_header.h>
"""
import sys

from fontTools.ttLib import TTFont

FONTS = [
    ("dejavu", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
    ("liberation", "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"),
]
CHARS = [0x41, 0x67]  # 'A', 'g'


def dump_font(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    glyf = f["glyf"]
    out = {"upem": f["head"].unitsPerEm, "num_glyphs": f["maxp"].numGlyphs}
    for cp in CHARS:
        gname = cmap[cp]
        gid = f.getGlyphID(gname)
        adv, _lsb = hmtx[gname]
        g = glyf[gname]
        if g.numberOfContours < 0:
            raise SystemExit("composite glyph in crosscheck set: " + gname)
        coords = g.coordinates
        flags = g.flags
        pts = [(int(x), int(y), int(fl) & 1) for (x, y), fl in zip(coords, flags)]
        out[cp] = {"gid": gid, "advance": int(adv), "ncontours": g.numberOfContours, "points": pts}
    return out


def main():
    out_path = sys.argv[1]
    L = [
        "/* AUTO-GENERATED by ttf_gen_expect.py -- fontTools ground truth.",
        " * Do not edit. */",
        "#ifndef TTF_EXPECT_H",
        "#define TTF_EXPECT_H",
        "",
        "typedef struct { int x, y, on_curve; } expect_pt;",
        "typedef struct {",
        "    int gid, advance, ncontours, npts;",
        "    const expect_pt *pts;",
        "} expect_glyph;",
        "typedef struct {",
        "    const char *path;",
        "    int upem, num_glyphs;",
        "    const expect_glyph **g;   /* indexed: 0='A', 1='g' */",
        "} expect_font;",
        "",
    ]
    for name, path in FONTS:
        d = dump_font(path)
        glyph_names = []
        for cp in CHARS:
            g = d[cp]
            parr = "expect_pts_%s_%02x" % (name, cp)
            L.append("static const expect_pt %s[] = {" % parr)
            for (x, y, oc) in g["points"]:
                L.append("    {%d,%d,%d}," % (x, y, oc))
            L.append("};")
            gname = "expect_g_%s_%02x" % (name, cp)
            glyph_names.append(gname)
            L.append(
                "static const expect_glyph %s = {%d,%d,%d,%d,%s};"
                % (gname, g["gid"], g["advance"], g["ncontours"],
                   len(g["points"]), parr))
        L.append(
            "static const expect_glyph *expect_gL_%s[] = {%s};"
            % (name, ",".join("&" + n for n in glyph_names)))
        L.append(
            'static const expect_font expect_%s = {"%s",%d,%d,expect_gL_%s};'
            % (name, path, d["upem"], d["num_glyphs"], name))
        L.append("")
    L += ["#endif /* TTF_EXPECT_H */", ""]
    with open(out_path, "w") as fh:
        fh.write("\n".join(L))
    print("wrote", out_path)


if __name__ == "__main__":
    main()
