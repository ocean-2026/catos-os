#!/usr/bin/env python3
"""
gen_ascii_font.py -- regenerate src/font_ascii.inc from the classic VGA
8x16 ROM font.

The kernel currently paints ASCII from an 8x8 public-domain table that is
stretched 2x vertically to fill the unified 8x16 cell.  That stretch is
what makes text look "thin / blocky" in graphics mode.  This script replaces
it with a NATIVE 8x16 font -- the classic IBM VGA / CP437 text-mode glyphs,
the same shapes a real PC shows in BIOS/DOS text mode 03.

Bitmaps are the well-known IBM VGA 8x16 ROM font (de facto public domain,
reproduced in every VGA BIOS).  The committed source of truth is
tools/font_8x16-linux.c (Linux's font_8x16.c, which carries the identical
bitmap rows under SPDX GPL-2.0 for the file wrapper); only the raw glyph
bytes are extracted here.  Cross-check: glyph 'A' == 00 00 10 38 6C C6 C6
FE C6 C6 C6 C6 00 00 00 00 -- the canonical IBM VGA 'A'.

The generated .inc is committed, so the kernel build needs neither Python
nor this script.

Usage:
    python kernel_v25/tools/gen_ascii_font.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "font_8x16-linux.c")
OUT = os.path.join(ROOT, "src", "font_ascii.inc")

HEADER = """\
/* auto-generated by tools/gen_ascii_font.py -- DO NOT EDIT.
 * Native IBM VGA 8x16 ASCII font, 16 row bytes per glyph, MSB = left pixel.
 * 95 printable glyphs, ASCII 0x20..0x7E, indexed by (ch - 0x20).
 *
 * SOURCE : classic IBM VGA / CP437 text-mode ROM font (de facto public
 *          domain bitmaps, identical to a real VGA BIOS).  Raw rows
 *          extracted from tools/font_8x16-linux.c (Linux font_8x16.c).
 * LICENSE: bitmap data is the canonical IBM VGA font, reproduced verbatim
 *          in virtually every VGA BIOS; no font foundry EULA applies.
 * INPUT  : tools/font_8x16-linux.c (committed)
 * Regenerate with: python kernel_v25/tools/gen_ascii_font.py
 */
static const unsigned char font_ascii[95][16] = {
"""


def parse_rows(path):
    """Return {codepoint: [16 byte values]} from a Linux font_8x16.c."""
    glyphs = {}
    cur_cp = None
    cur_rows = []
    # glyph marker: /* 32 0x20 ' ' */  (decimal and/or hex codepoint)
    marker = re.compile(r"/\*\s*(?:(\d+)\s+)?0x([0-9A-Fa-f]{2})\s*'")
    byte_re = re.compile(r"0x([0-9A-Fa-f]{2})")
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            m = marker.search(line)
            if m and "0x00" not in m.group(0):
                if cur_cp is not None and len(cur_rows) == 16:
                    glyphs[cur_cp] = cur_rows
                hexcp = int(m.group(2), 16)
                cur_cp = int(m.group(1)) if m.group(1) else hexcp
                if cur_cp != hexcp:
                    raise SystemExit("cp mismatch: %d vs %02X" % (cur_cp, hexcp))
                cur_rows = []
                continue
            if cur_cp is not None and len(cur_rows) < 16:
                b = byte_re.search(line)
                if b and "0x" in line and "/*" not in line.split("0x")[0]:
                    cur_rows.append(int(b.group(1), 16))
    if cur_cp is not None and len(cur_rows) == 16:
        glyphs[cur_cp] = cur_rows
    return glyphs


def main():
    glyphs = parse_rows(SRC)
    missing = [cp for cp in range(0x20, 0x7F) if cp not in glyphs]
    if missing:
        raise SystemExit("missing glyphs: %s" %
                         " ".join("%02X" % c for c in missing))
    # sanity: canonical IBM VGA 'A'
    a = glyphs[0x41]
    expect = [0x00, 0x00, 0x10, 0x38, 0x6C, 0xC6, 0xC6, 0xFE,
              0xC6, 0xC6, 0xC6, 0xC6, 0x00, 0x00, 0x00, 0x00]
    if a != expect:
        raise SystemExit("'A' does not match canonical IBM VGA bitmap")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        for cp in range(0x20, 0x7F):
            ch = chr(cp)
            label = "'%s'" % ch.replace("\\", "\\\\").replace("'", "\\'")
            # printable comment only
            if not (32 <= cp <= 126):
                label = "?"
            f.write("    {")
            f.write(",".join("0x%02X" % b for b in glyphs[cp]))
            f.write("}, /* %02X %s */\n" % (cp, label))
        f.write("};\n")
    print("wrote %s (95 glyphs x 16 rows)" % OUT)


if __name__ == "__main__":
    main()
