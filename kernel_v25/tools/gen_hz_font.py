#!/usr/bin/env python3
"""
gen_hz_font.py -- regenerate src/font_hz.inc from the committed Unifont subset.

The kernel ships 16x16 1bpp bitmaps for all 6763 GB2312 hanzi.  The source
of those bitmaps is GNU Unifont 16.0.01, dual-licensed under

    GPLv2+ with the GNU Font Embedding Exception  OR  SIL OFL 1.1

so embedding the derived bitmaps in a CatOS kernel image is explicitly
permitted (including in non-free software).  v2.8 used bitmaps rendered
from a proprietary Windows font; those were replaced precisely because
their EULA made redistribution of the kernel image questionable.
Full license texts: tools/UNIFONT-LICENSE.txt and tools/OFL-1.1.txt.

The subset file `unifont-gb2312.hex` is committed, so regeneration needs
NO network, NO Pillow, NO installed CJK font and NO third-party code.
The kernel build itself needs nothing at all -- it just compiles the
committed .inc.

Format of the .hex lines (GNU Unifont convention):
    4E2D:01000100010001003FF82108...   (16 rows x 16 bits = 64 hex digits)

Usage:
    python kernel_v25/tools/gen_hz_font.py
    python kernel_v25/tools/gen_hz_font.py --from-full /path/unifont.hex
        (rebuild the committed subset from a full Unifont .hex first)

To refresh from upstream (optional, needs network):
    curl -L -o /tmp/u.hex.gz https://unifoundry.com/pub/unifont/\\
unifont-16.0.01/font-builds/unifont-16.0.01.hex.gz
    gunzip -c /tmp/u.hex.gz > /tmp/u.hex
    python kernel_v25/tools/gen_hz_font.py --from-full /tmp/u.hex
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SUBSET = os.path.join(HERE, "unifont-gb2312.hex")
OUT = os.path.join(ROOT, "src", "font_hz.inc")

HEADER = """\
/* auto-generated by tools/gen_hz_font.py -- DO NOT EDIT.
 * 16x16 1bpp hanzi bitmaps, 32 bytes per glyph, MSB = left pixel.
 * Sorted by Unicode codepoint; lookup via binary search.
 *
 * SOURCE : GNU Unifont 16.0.01 (unifont-16.0.01.hex.gz), GB2312 subset
 *          https://unifoundry.com/pub/unifont/unifont-16.0.01/
 * LICENSE: dual-licensed -- GPLv2+ with the GNU Font Embedding Exception,
 *          or SIL Open Font License 1.1.  Embedding these bitmaps in a
 *          kernel image is permitted, including in non-free software.
 *          Full texts: tools/UNIFONT-LICENSE.txt, tools/OFL-1.1.txt
 * INPUT  : tools/unifont-gb2312.hex (committed; offline, no dependencies)
 *
 * Regenerate with: python kernel_v25/tools/gen_hz_font.py
 * The kernel build depends on neither Python nor any font file.
 */
#include <stdint.h>
typedef struct { uint16_t cp; uint8_t bits[32]; } hz_glyph_t;
static const hz_glyph_t hz_font[] = {
"""


def gb2312_codepoints():
    """All 6763 hanzi in GB2312 levels 1+2, as Unicode codepoints."""
    out = set()
    for qu in range(0xB0, 0xF8):
        for wei in range(0xA1, 0xFF):
            try:
                out.add(ord(bytes([qu, wei]).decode("gb2312")))
            except UnicodeDecodeError:
                pass
    return out


def read_hex(path):
    glyphs = {}
    with open(path, encoding="ascii") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or ":" not in line:
                continue
            cps, hx = line.split(":", 1)
            try:
                cp = int(cps, 16)
            except ValueError:
                continue
            if len(hx) == 32:          # 8x16 halfwidth: pad to 16x16
                hx = "".join(hx[i * 4:i * 4 + 4] + "0000" for i in range(8))
            if len(hx) != 64:
                continue
            glyphs[cp] = bytes.fromhex(hx)
    return glyphs


def rebuild_subset(full_hex_path):
    glyphs = read_hex(full_hex_path)
    wanted = gb2312_codepoints()
    missing = sorted(c for c in wanted if c not in glyphs)
    if missing:
        sys.exit("ERROR: full Unifont .hex lacks %d GB2312 glyphs "
                 "(first: U+%04X)" % (len(missing), missing[0]))
    with open(SUBSET, "w", encoding="ascii", newline="\n") as fh:
        fh.write("# GNU Unifont 16.0.01 - GB2312 hanzi subset (%d glyphs)\n"
                 % len(wanted))
        fh.write("# Source: https://unifoundry.com/pub/unifont/"
                 "unifont-16.0.01/font-builds/unifont-16.0.01.hex.gz\n")
        fh.write("# License: GPLv2+ with GNU Font Embedding Exception "
                 "OR SIL OFL 1.1\n")
        fh.write("#          (see UNIFONT-LICENSE.txt and OFL-1.1.txt "
                 "in this directory)\n")
        for cp in sorted(wanted):
            fh.write("%04X:%s\n" % (cp, glyphs[cp].hex().upper()))


def main():
    args = sys.argv[1:]
    if args[:1] == ["--from-full"]:
        if len(args) != 2:
            sys.exit("usage: gen_hz_font.py --from-full <unifont.hex>")
        rebuild_subset(args[1])
        print("rebuilt subset from", args[1])

    glyphs = read_hex(SUBSET)
    wanted = gb2312_codepoints()
    missing = [c for c in sorted(wanted) if c not in glyphs]
    if missing:
        sys.exit("ERROR: subset lacks U+%04X and %d more; "
                 "run --from-full with a complete Unifont .hex"
                 % (missing[0], len(missing)))

    parts = [HEADER]
    for cp in sorted(wanted):
        bits = ",".join(str(b) for b in glyphs[cp])
        parts.append("    {0x%04X,{%s}},\n" % (cp, bits))
    parts.append("};\n")
    parts.append("#define HZ_FONT_COUNT ((unsigned)"
                 "(sizeof(hz_font)/sizeof(hz_font[0])))\n")
    with open(OUT, "w", encoding="ascii", newline="\n") as fh:
        fh.write("".join(parts))
    print("wrote %s: %d glyphs (%d bytes of bitmap data)"
          % (OUT, len(wanted), len(wanted) * 32))


if __name__ == "__main__":
    main()
