#!/usr/bin/env python3
"""
gen_hz_font.py -- generate the GB2312 16x16 bitmap font for CatOS.

Renders every GB2312 hanzi (qu 0xB0..0xF7, wei 0xA1..0xFE, 6763 glyphs)
with a CJK TrueType font into a 16x16 1-bit bitmap, then emits
src/font_hz.inc as a sorted-by-codepoint C table for binary search.

Dependencies (BUILD TIME ONLY):
    Pillow  (python -m pip install --target <dir> Pillow)
    a CJK font -- Windows simsun.ttc / simhei.ttf by default

The generated .inc is committed to the repository.  The kernel build needs
NEITHER Pillow NOR the font, so no third-party data enters the build.

Usage:
    PYTHONPATH=/tmp/catos_pil python kernel_v25/tools/gen_hz_font.py

Licensing note: the bitmaps are derived from a locally installed font.
They are fine for local/private use; check the font EULA before shipping
a kernel image that embeds them publicly.
"""
import os
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    sys.exit("ERROR: Pillow is required to regenerate the font "
             "(the committed src/font_hz.inc needs nothing).")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "font_hz.inc")

FONT_CANDIDATES = [
    r"C:\Windows\Fonts\simsun.ttc",
    r"C:\Windows\Fonts\simhei.ttf",
    r"C:\Windows\Fonts\msyh.ttc",
    "/usr/share/fonts/truetype/arphic/uming.ttc",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
]
SIZE = 16


def load_font():
    for p in FONT_CANDIDATES:
        if os.path.exists(p):
            try:
                return ImageFont.truetype(p, SIZE, index=0), p
            except Exception:
                continue
    sys.exit("ERROR: no usable CJK TrueType font found")


def enumerate_hanzi():
    seen = {}
    for qu in range(0xB0, 0xF8):
        for wei in range(0xA1, 0xFF):
            try:
                ch = bytes([qu, wei]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            cp = ord(ch)
            if cp in seen:
                continue
            seen[cp] = ch
    return sorted(seen.items())


def render_glyph(ch, font):
    im = Image.new("1", (SIZE, SIZE), 0)
    d = ImageDraw.Draw(im)
    d.text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(SIZE):
        v = 0
        for x in range(SIZE):
            v = (v << 1) | (1 if im.getpixel((x, y)) else 0)
        rows.append((v >> 8) & 0xFF)
        rows.append(v & 0xFF)
    return rows


def main():
    font, path = load_font()
    chars = enumerate_hanzi()
    print("font: %s" % path)
    print("glyphs: %d (U+%04X .. U+%04X)" %
          (len(chars), chars[0][0], chars[-1][0]))

    blank = 0
    table = []
    for cp, ch in chars:
        bits = render_glyph(ch, font)
        if not any(bits):
            blank += 1
        table.append((cp, bits))
    if blank:
        print("WARNING: %d empty glyphs" % blank)

    lines = [
        "/* auto-generated by tools/gen_hz_font.py -- DO NOT EDIT.",
        " * GB2312 hanzi, 16x16 1bpp, 32 bytes per glyph, MSB = left pixel.",
        " * Sorted by Unicode codepoint; lookup via binary search.",
        " * Source font: %s at %d px." % (os.path.basename(path), SIZE),
        " * Regenerate only when the font or coverage changes; the build",
        " * does not depend on Pillow or on any font file.",
        " */",
        "#include <stdint.h>",
        "typedef struct { uint16_t cp; uint8_t bits[32]; } hz_glyph_t;",
        "static const hz_glyph_t hz_font[] = {",
    ]
    for cp, bits in table:
        lines.append("    {0x%04X,{%s}}," %
                     (cp, ",".join(str(b) for b in bits)))
    lines += [
        "};",
        "#define HZ_FONT_COUNT ((unsigned)(sizeof(hz_font)/sizeof(hz_font[0])))",
        "",
    ]
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("OK -> %s (%d bytes, %d glyphs)" %
          (OUT, os.path.getsize(OUT), len(table)))


if __name__ == "__main__":
    main()
