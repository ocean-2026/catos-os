#!/usr/bin/env python3
"""gen_symtab.py -- build-time kernel symbol table for the crash screen.

The BSOD resolves EIP / stack frames to "function+offset" without a runtime
kallsyms.  This script reads the linked PE's symbol table with `nm`, keeps
the CODE symbols (T/t), strips the PE leading underscore, sorts by address
and emits `src/symtab.inc`: a compact address/name table in .rodata.

Address layout (pe.ld): everything links at 0x1000000; the PE symbol
addresses already carry that image base, so they match the runtime EIPs
directly.  The table is static const: no heap, no lookup allocations on the
crash path.

Usage:  python3 gen_symtab.py <kernel.pe> <out.inc>
"""
import os
import subprocess
import sys


def strip_uscore(name):
    return name[1:] if name.startswith("_") else name


def main():
    pe = sys.argv[1]
    out = sys.argv[2]

    nm = os.environ.get("NM", "nm")
    try:
        raw = subprocess.run([nm, pe], capture_output=True, text=True,
                              check=True).stdout
    except Exception as exc:
        # No nm available: emit an empty table rather than breaking the build.
        print("gen_symtab: nm failed (%s); empty symtab emitted" % exc,
              file=sys.stderr)
        raw = ""

    entries = []
    seen = set()
    for line in raw.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        addr, typ, name = parts
        if typ not in ("T", "t"):
            continue
        if not all(ch in "0123456789abcdefABCDEF" for ch in addr):
            continue
        addr_i = int(addr, 16)
        name = strip_uscore(name)
        if not name or name in seen:
            continue
        seen.add(name)
        entries.append((addr_i, name))

    entries.sort(key=lambda e: e[0])

    lines = [
        "/* auto-generated by tools/gen_symtab.py -- DO NOT EDIT.",
        " * CODE symbols (T/t) from the linked kernel.pe, sorted by address.",
        " * Used by bsod.c to resolve EIP/stack frames to nearest symbol+offset.",
        " */",
        "#include <stdint.h>",
        "typedef struct { uint32_t addr; const char *name; } sym_t;",
        "static const sym_t g_symtab[] = {",
    ]
    for addr, name in entries:
        safe = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    { 0x%08Xu, "%s" },' % (addr, safe))
    lines.append("};")
    lines.append("static const unsigned g_symtab_n = %u;" % len(entries))
    lines.append("")

    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    os.replace(tmp, out)
    print("gen_symtab: %d symbols -> %s" % (len(entries), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
