#ifndef IME_H
#define IME_H

/*
 * ime.h -- minimal pinyin IME over the US-QWERTY keyboard (v2.58 stage 1).
 *
 * F2 toggles it.  While active, letter keys build a pinyin composition
 * string that is shown INLINE at the input cursor (readline draft line or
 * editor cursor) -- it never occupies the candidate area.  The fixed
 * bottom two rows hold a separator line and the candidate list:
 *
 *   1.好 2.号 3.浩 ...
 *
 * Digits 1..9 pick a candidate, Space picks the first, - = [ ] (and the
 * Left/Right arrows) page, Esc cancels, Backspace edits the composition,
 * Enter commits the raw pinyin string.  The two bottom rows are saved and
 * restored verbatim by the display front-end, so the bar never destroys
 * shell output or editor content.
 *
 * Data: src/pinyin.inc (generated by tools/gen_pinyin.py offline, committed,
 * no build-time Python dependency).
 */

#define IME_PASS     0     /* key not consumed -- caller handles it */
#define IME_CONSUME  1     /* key consumed, nothing committed       */
#define IME_COMMIT   2     /* *out holds UTF-8 text + NUL           */

/* Committed text buffer: up to 8 hanzi (3 B each) or a raw pinyin string. */
#define IME_OUT_MAX  25

int  ime_active(void);
int  ime_feed(int key, char out[IME_OUT_MAX]);
void ime_refresh(void);                /* repaint the area after a redraw */
void ime_set_anchor(int row);          /* retained stub (stage-1 fixed rows) */
void ime_off(void);                    /* force-close area + deactivate   */
/* Current inline composition string (empty when inactive / cleared).
 * The readline draft and the editor append this at the cursor while the
 * IME is active; it disappears on commit / cancel. */
const char *ime_composition(void);

#endif
