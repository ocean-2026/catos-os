#!/usr/bin/env python3
"""gen_builtin.py - embed the CE apps and developer docs into the kernel.

Reads build/apps.list (shared with build.sh), extapp/bin/*.ce and
extapp/docs/*.txt and emits src/builtin_apps.inc: C arrays + a
builtin_files[] table.  The kernel compiles this in and
ce_install_builtins() copies the files onto the FAT32 volume
(/bin, /appdevelop) after format or at boot.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "builtin_apps.inc")

LIST = os.path.join(ROOT, "build", "apps.list")
PKG_LIST = os.path.join(ROOT, "build", "pkg.list")


def app_names():
    """Single source of truth shared with build.sh."""
    with open(LIST, "r") as fh:
        for line in fh:
            name = line.strip()
            if name and not name.startswith("#"):
                yield name


def packages():
    """P4 package index: name|version|desc|file|cmd (build/pkg.list).

    Returns a list of dicts.  Payload .catpkg files live in
    extapp/pkg/ and are produced by tools/mkpkg.py during build.sh.
    """
    out = []
    if not os.path.exists(PKG_LIST):
        return out
    with open(PKG_LIST, "r") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("|")
            if len(parts) != 5:
                print("ERROR: bad pkg.list line: %s" % line, file=sys.stderr)
                sys.exit(1)
            name, version, desc, file, cmd = [p.strip() for p in parts]
            out.append({"name": name, "version": version, "desc": desc,
                        "file": file, "cmd": cmd,
                        "src": os.path.join(ROOT, "extapp", "pkg", file)})
    return out


# Compiled by build.sh from build/apps.list.  Adding an app no longer
# requires editing this file as well.
FILES = [("/bin/%s.ce" % name,
          os.path.join(ROOT, "extapp", "bin", name + ".ce"))
         for name in app_names()]

# Files NOT produced from apps.list: a prebuilt ELF, developer docs and
# the Stage 2A CSO1 shared object.
FILES += [
    ("/bin/hello.elf",           os.path.join(ROOT, "extapp", "bin", "hello.elf")),
    ("/bin/libmath.so",          os.path.join(ROOT, "extapp", "bin", "libmath.so")),
    ("/appdevelop/API.TXT",      os.path.join(ROOT, "extapp", "docs", "API.txt")),
    ("/appdevelop/CEFORMAT.TXT", os.path.join(ROOT, "extapp", "docs", "CEFORMAT.txt")),
]

# Optional extras: embedded when the file exists, skipped (with a note)
# otherwise.  node.ce is built separately in build.sh; the rest are
# hand-written scripts/docs that a partial tree may not have.
OPTIONAL = [
    ("/bin/node.ce",           os.path.join(ROOT, "node", "node.ce")),
    ("/bin/TEST.JS",           os.path.join(ROOT, "node", "TEST.JS")),
    ("/appdevelop/HELLO.C",    os.path.join(ROOT, "extapp", "docs", "hello_c.txt")),
    ("/bin/OCNTOOLS.CFG",      os.path.join(ROOT, "extapp", "ocntools.cfg")),
    ("/bin/DEMO." + chr(99) + chr(115) + chr(99),
                               os.path.join(ROOT, "extapp", "DEMO.csc")),
    ("/bin/DEMO1.TAD",         os.path.join(ROOT, "extapp", "demo1.tad")),
    ("/bin/DEMO2.TAD",         os.path.join(ROOT, "extapp", "demo2.tad")),
    ("/bin/DEMO.GO",           os.path.join(ROOT, "extapp", "cases", "DEMO.GO")),
    ("/bin/TEST.GO",           os.path.join(ROOT, "extapp", "cases", "TEST.GO")),
    ("/bin/MINI_GO.GO",        os.path.join(ROOT, "extapp", "cases", "MINI_GO.GO")),
    ("/bin/MINI_IN.GO",        os.path.join(ROOT, "extapp", "cases", "MINI_IN.GO")),
    ("/bin/SYN.GO",            os.path.join(ROOT, "extapp", "cases", "SYN.GO")),
]

def c_ident(path):
    ident = "blt"
    for ch in path:
        if ch.isalnum():
            ident += ch
        else:
            ident += "_"
    return ident

# P4 packaged apps: embedded under /pkg/ on the volume; `pkg install`
# copies the selected payload into /bin.  Mirrored for mkdisk.py below.
PACKAGES = packages()
PKG_FILES = [("/pkg/%s" % p["file"], p["src"]) for p in PACKAGES]


def main():
    selected = list(FILES)
    for path, src in OPTIONAL:
        if os.path.exists(src):
            selected.append((path, src))
        else:
            print("note: skipping %s (not built: %s)" % (path, src))
    pkg_selected = list(PKG_FILES)
    lines = []
    lines.append("/* auto-generated by build/gen_builtin.py - do not edit */")
    lines.append("#include <stdint.h>")

    def emit_blob(path, src):
        if not os.path.exists(src):
            print("ERROR: missing " + src, file=sys.stderr)
            sys.exit(1)
        with open(src, "rb") as fh:
            data = fh.read()
        ident = c_ident(path)
        lines.append("static const unsigned char %s[] = {" % ident)
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("    " + ",".join("0x%02x" % b for b in chunk) + ",")
        lines.append("};")
        return ident, len(data)

    blobs = []
    for path, src in selected:
        blobs.append((path, src, emit_blob(path, src)))
    pkg_blobs = []
    for path, src in pkg_selected:
        pkg_blobs.append((path, src, emit_blob(path, src)))

    lines.append("")
    lines.append("typedef struct { const char *path; const unsigned char *data; unsigned int len; } builtin_file_t;")
    lines.append("static const builtin_file_t builtin_files[] = {")
    for path, src, (ident, n) in blobs:
        lines.append('    {"%s", %s, %d},' % (path, ident, n))
    lines.append("};")

    # P4 package payloads + index metadata (consumed by the `pkg` shell cmds)
    lines.append("")
    lines.append("typedef struct { const char *name; const char *version; "
                 "const char *desc; const char *cmd; const char *file; } pkg_meta_t;")
    lines.append("static const pkg_meta_t pkg_meta[] = {")
    for p in PACKAGES:
        lines.append('    {"%s", "%s", "%s", "%s", "%s"},'
                     % (p["name"], p["version"], p["desc"], p["cmd"], p["file"]))
    lines.append("};")
    lines.append("static const builtin_file_t pkg_files[] = {")
    for path, src, (ident, n) in pkg_blobs:
        lines.append('    {"%s", %s, %d},' % (path, ident, n))
    lines.append("};")
    with open(OUT, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    total = sum(os.path.getsize(s) for _, s in selected + pkg_selected)
    print("OK -> src/builtin_apps.inc (%d builtin, %d packages, %d bytes)"
          % (len(selected), len(pkg_selected), total))

if __name__ == "__main__":
    main()
