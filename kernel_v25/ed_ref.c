/* ed_ref.c -- host reference for the kernel-env Ed25519 fixed-vector probe.
 * Same fixed sk and message as the SSHD_DEBUG block in ssh.c.
 * Build: gcc -m32 -O2 -std=c99 -Iinclude ed_ref.c src/crypto.c -o build/ed_ref
 */
#include <stdio.h>
#include "../include/crypto.h"

static const uint8_t tsk[64] = {
    0x01,0x0f,0x1d,0x2b,0x39,0x47,0x55,0x63,
    0x71,0x7f,0x8d,0x9b,0xa9,0xb7,0xc5,0xd3,
    0xe1,0xef,0xfd,0x0b,0x19,0x27,0x35,0x43,
    0x51,0x5f,0x6d,0x7b,0x89,0x97,0xa5,0xb3,
    0xC0,0xC1,0xC2,0xC3,0xC4,0xC5,0xC6,0xC7,
    0xC8,0xC9,0xCA,0xCB,0xCC,0xCD,0xCE,0xCF,
    0xD0,0xD1,0xD2,0xD3,0xD4,0xD5,0xD6,0xD7,
    0xD8,0xD9,0xDA,0xDB,0xDC,0xDD,0xDE,0xDF
};

int main(void) {
    uint8_t tsig[64], abc[64];
    int i;
    crypto_ed25519_sign(tsig, (const uint8_t *)"hello", 5, tsk);
    crypto_sha512(abc, (const uint8_t *)"abc", 3);
    printf("sk0  ");
    for (i = 0; i < 32; i++) printf("%02x", tsk[i]);
    printf("\nsig  ");
    for (i = 0; i < 32; i++) printf("%02x", tsig[i]);
    printf("\nsig2 ");
    for (i = 32; i < 64; i++) printf("%02x", tsig[i]);
    printf("\ns512 ");
    for (i = 0; i < 16; i++) printf("%02x", abc[i]);
    printf("\n");
    return 0;
}
